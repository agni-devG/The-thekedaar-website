    <script>
        // Intersection Observer for scroll animations
        document.addEventListener('DOMContentLoaded', function() {
            const animatedElements = document.querySelectorAll('.fade-in, .slide-in-left, .slide-in-right, .scale-in, .stagger-children, .hero-content-container, .highlight-text');
            
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('visible');
                        // Stop observing after animation triggers
                        observer.unobserve(entry.target);
                    }
                });
            }, {
                threshold: 0.1,
                rootMargin: '0px 0px -50px 0px'
            });
            
            animatedElements.forEach(element => {
                observer.observe(element);
            });
            
            // Animate hero section immediately on load
            const heroContent = document.querySelector('.hero-content-container');
            const highlightText = document.querySelector('.highlight-text');
            if (heroContent) {
                setTimeout(() => {
                    heroContent.classList.add('visible');
                }, 300);
                
                // Animate highlight text with a slight delay
                setTimeout(() => {
                    if (highlightText) {
                        highlightText.classList.add('visible');
                    }
                }, 1000);
            }
            
            // Add hover effect to gallery items
            const galleryItems = document.querySelectorAll('.gallery-item');
            galleryItems.forEach(item => {
                item.addEventListener('mouseenter', () => {
                    item.style.transform = 'scale(1.02)';
                    item.style.transition = 'transform 0.3s ease';
                });
                
                item.addEventListener('mouseleave', () => {
                    item.style.transform = 'scale(1)';
                });
            });
        });
    </script>
    
